"""POST /api/analyze — validate a GitHub URL and return repository evidence.

The handler is a plain ``def`` so FastAPI runs the blocking PyGithub/requests
calls in its worker threadpool instead of blocking the event loop.
"""
from fastapi import APIRouter, HTTPException

from api.schemas import AnalyzeRequest, AnalyzeResponse
from hackpack.engine.repo_analyzer import RepositoryAnalysisError, analyze_repository
from hackpack.engine.evidence_store import summarize_evidence

router = APIRouter(tags=["analysis"])


@router.post("/analyze", response_model=AnalyzeResponse)
def analyze(request: AnalyzeRequest) -> AnalyzeResponse:
    try:
        evidence = analyze_repository(request.repo_url.strip())
    except RepositoryAnalysisError as exc:
        # Message is generated by our own code and contains no tokens.
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    return AnalyzeResponse(evidence=evidence, summary=summarize_evidence(evidence))
