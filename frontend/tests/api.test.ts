import { describe, expect, it } from 'vitest'
import {
  buildGeneratePayload,
  buildPitchPayload,
  mapBackendDeckToDraft,
  normalizeAnalysisResponse,
} from '../src/lib/api'
import type { PitchDraft, ProjectFormState, RepositoryAnalysis } from '../src/types/hackpack'

const evidence: RepositoryAnalysis = {
  repositoryUrl: 'https://github.com/octocat/hello-world',
  repositoryName: 'hello-world',
  description: 'A demo repository',
  primaryLanguage: 'TypeScript',
  languages: [{ name: 'TypeScript', bytes: 1024 }],
  techStack: [],
  keyModules: [],
  files: ['README.md'],
  signals: [],
  demoUrls: [],
  warnings: ['The analysis time budget was reached.'],
  unknowns: [],
  raw: { repo_url: 'https://github.com/octocat/hello-world', repo_name: 'hello-world' },
}

const makeDraft = (overrides: Partial<PitchDraft> = {}): PitchDraft => ({
  projectName: 'hello-world',
  tagline: 'A demo project',
  durationMinutes: 3,
  generationMode: 'fallback',
  generationSource: 'local',
  warnings: ['Reviewed before presenting.'],
  slides: Array.from({ length: 6 }, (_, index) => ({
    id: `slide-${index + 1}`,
    title: index === 0 ? '' : `Slide ${index + 1}`, // slide 1 title cleared on purpose
    subtitle: '',
    bullets: ['One point', 'Two point', 'Three point', 'Four point', 'Five point', 'Six point', 'Seven point'],
    speakerNotes: 'Notes'.padEnd(5000, '!'), // over the 4000-char backend limit
    seconds: index === 0 ? 0 : 30, // 0 is below the backend minimum of 5
    claims: [
      {
        id: `claim-${index + 1}-0`,
        statement: 'x'.repeat(500), // over the 400-char backend limit
        status: 'unknown',
        action: 'y'.repeat(600), // over the 500-char backend limit
      },
    ],
  })),
  ...overrides,
})

describe('generate payload contract', () => {
  it('sends the deck under the `deck` key the FastAPI backend expects', () => {
    const payload = buildGeneratePayload({ evidence, pitch: makeDraft(), form: {} as never })
    expect(payload).toHaveProperty('deck')
    expect(payload).not.toHaveProperty('pitch_deck')
    expect(payload).not.toHaveProperty('project_context')
    expect(payload.evidence).toBe(evidence.raw)
    expect(payload.demo_duration_seconds).toBe(120)
  })

  it('clamps every slide into the backend validation limits', () => {
    const payload = buildGeneratePayload({ evidence, pitch: makeDraft(), form: {} as never })
    const deck = payload.deck as Record<string, unknown>
    const slides = deck.slides as Array<Record<string, unknown>>
    expect(slides).toHaveLength(6)
    expect(slides[0].title).toBe('Slide 1') // empty title gets a fallback
    expect(slides[0].speaking_time_seconds).toBe(5) // 0 raised to the minimum
    expect((slides[0].speaker_notes as string).length).toBeLessThanOrEqual(4000)
    expect(slides[0].bullet_points).toHaveLength(5) // extra bullets dropped
    expect(deck.total_duration_seconds).toBe(slides.reduce(
      (sum, slide) => sum + (slide.speaking_time_seconds as number), 0,
    ))
    const claim = (slides[0].claims as Array<Record<string, unknown>>)[0]
    expect((claim.statement as string).length).toBeLessThanOrEqual(400)
    expect((claim.needs_action as string).length).toBeLessThanOrEqual(500)
    expect(claim.evidence_type).toBe('needs_verification') // `unknown` is never sent to the backend
  })

  it('labels local drafts as fallback and passes AI drafts through', () => {
    const local = buildGeneratePayload({ evidence, pitch: makeDraft(), form: {} as never })
    expect((local.deck as Record<string, unknown>).generation_mode).toBe('fallback')
    const ai = buildGeneratePayload({
      evidence,
      pitch: makeDraft({ generationMode: 'ai', generationSource: 'backend' }),
      form: {} as never,
    })
    expect((ai.deck as Record<string, unknown>).generation_mode).toBe('ai')
  })

  it('collects unverified claims with a review action', () => {
    const payload = buildGeneratePayload({ evidence, pitch: makeDraft(), form: {} as never })
    const unverified = (payload.deck as Record<string, unknown>).unverified_claims as Array<Record<string, unknown>>
    expect(unverified).toHaveLength(6)
    expect(unverified[0].evidence_type).toBe('needs_verification')
    expect(unverified[0].needs_action).toBeTruthy()
    expect(unverified[0].confidence).toBe(0)
  })
})

describe('backend deck mapping', () => {
  const backendDeck = {
    project_name: 'hello-world',
    tagline: 'From the backend',
    total_duration_seconds: 180,
    generation_mode: 'fallback',
    generation_warnings: ['Generated by the deterministic template fallback.'],
    slides: [
      {
        slide_number: 1,
        title: 'The problem',
        subtitle: null,
        bullet_points: ['A problem'],
        speaker_notes: 'Open with the problem.',
        speaking_time_seconds: 30,
        claims: [
          {
            statement: 'The repository contains an app entry point',
            evidence_type: 'repo_evidence',
            source: 'app/main.py',
            line_start: 1,
            line_end: 3,
            needs_action: 'Confirm with a live demo.',
          },
        ],
      },
      ...Array.from({ length: 5 }, (_, index) => ({
        slide_number: index + 2,
        title: `Slide ${index + 2}`,
        subtitle: null as string | null,
        bullet_points: [],
        speaker_notes: '',
        speaking_time_seconds: 30,
        claims: [],
      })),
    ],
    unverified_claims: [],
  }

  it('maps snake_case deck fields into the editable draft shape', () => {
    const draft = mapBackendDeckToDraft(backendDeck, ['Analyzer warning.'])
    expect(draft.projectName).toBe('hello-world')
    expect(draft.generationMode).toBe('fallback')
    expect(draft.generationSource).toBe('backend')
    expect(draft.durationMinutes).toBe(3)
    expect(draft.slides).toHaveLength(6)
    expect(draft.slides[0].id).toBe('slide-1')
    expect(draft.slides[0].seconds).toBe(30)
    expect(draft.slides[0].claims[0]).toMatchObject({
      status: 'repo_evidence',
      source: 'app/main.py',
      lineStart: 1,
      lineEnd: 3,
      action: 'Confirm with a live demo.',
    })
    expect(draft.warnings).toContain('Analyzer warning.')
    expect(draft.warnings).toContain('Generated by the deterministic template fallback.')
  })

  it('treats unrecognised evidence types as needing verification', () => {
    const tampered = {
      ...backendDeck,
      slides: backendDeck.slides.map((slide, index) => index === 0
        ? { ...slide, claims: [{ statement: 'A suspicious claim', evidence_type: 'definitely_proven' }] }
        : slide),
    }
    const draft = mapBackendDeckToDraft(tampered)
    expect(draft.slides[0].claims[0].status).toBe('needs_verification')
  })

  it('reports a non-six-slide deck as empty so callers can fall back', () => {
    const draft = mapBackendDeckToDraft({ project_name: 'x', slides: [] })
    expect(draft.slides).toHaveLength(0)
  })
})

describe('pitch payload contract', () => {
  const form: ProjectFormState = {
    repoUrl: 'https://github.com/octocat/hello-world',
    eventName: 'Open Innovation Challenge',
    eventBrief: 'Build a useful tool for the community.'.repeat(30), // > 400 chars
    judgingCriteria: 'Innovation\nTechnical implementation\n',
    pitchDurationMinutes: 1.5, // not representable as the backend's integer minutes
    requiredDeliverables: ['Pitch deck'],
    additionalRules: '3-minute pitch',
    problemStatement: 'Volunteers lose hours to manual sorting.',
    targetUsers: 'Shelter staff',
    solutionDescription: 'One scan sorts a donation pile.',
    measuredResults: 'We sorted 40 boxes in a pilot.',
    expectedImpact: 'Cut sorting time in half.',
    futurePlans: 'Add multilingual labels.',
    teamMembers: 'Alex, Sam',
    demoUrl: '',
  }

  it('maps the form onto brief + team within backend limits', () => {
    const { brief, team } = buildPitchPayload(form)
    expect(brief.event_name).toBe('Open Innovation Challenge')
    expect((brief.theme as string).length).toBeLessThanOrEqual(400)
    expect(brief.judging_criteria).toEqual(['Innovation', 'Technical implementation'])
    expect(brief.pitch_duration_minutes).toBe(2) // 1.5 rounds to a valid integer
    expect(team.problem_statement).toBe('Volunteers lose hours to manual sorting.')
    expect(team.solution_summary).toBe('One scan sorts a donation pile.')
    expect(team.key_results).toBe('We sorted 40 boxes in a pilot.')
    expect(team.impact_claims).toEqual(['Cut sorting time in half.'])
    expect(team.team_members).toEqual(['Alex', 'Sam'])
  })

  it('defaults safely on an empty form', () => {
    const { brief, team } = buildPitchPayload({
      repoUrl: '', eventName: '', eventBrief: '', judgingCriteria: '', pitchDurationMinutes: 3,
      requiredDeliverables: [], additionalRules: '', problemStatement: '', targetUsers: '',
      solutionDescription: '', measuredResults: '', expectedImpact: '', futurePlans: '',
      teamMembers: '', demoUrl: '',
    })
    expect(brief.event_name).toBe('Hackathon')
    expect(team.problem_statement).toBe('')
    expect(team.key_results).toBeNull()
    expect(team.impact_claims).toEqual([])
  })
})

describe('analysis warnings mapping', () => {
  it('surfaces analyzer warnings from the evidence object and summary', () => {
    const normalized = normalizeAnalysisResponse({
      evidence: {
        repo_url: 'https://github.com/octocat/hello-world',
        repo_name: 'hello-world',
        file_tree: ['README.md'],
        analysis_warnings: ['Analyzed a bounded subset of files.'],
      },
      summary: { warnings: ['The analysis time budget was reached.'] },
    }, 'https://github.com/octocat/hello-world')
    expect(normalized.warnings).toContain('Analyzed a bounded subset of files.')
    expect(normalized.warnings).toContain('The analysis time budget was reached.')
  })
})
