"""Regenerate sample_output/ with synthetic, clearly labelled data.

Run from the repository root::

    python scripts/make_sample_output.py

The generated "OpenCycle" project does not exist; every file is synthetic and
the notice in the folder says so. No real-world statistics are included.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from hackpack.models import HackathonBrief, RepoEvidence, TeamContext, TechStackItem  # noqa: E402
from hackpack.engine.pitch_builder import build_fallback_pitch  # noqa: E402
from hackpack.engine.verifier import verify_claims  # noqa: E402
from hackpack.generators.pptx_engine import generate_pptx  # noqa: E402
from hackpack.generators.script_engine import generate_script  # noqa: E402
from hackpack.generators.demo_engine import build_demo_plan, generate_demo_checklist  # noqa: E402

OUT = ROOT / "sample_output"

SYNTHETIC_EVIDENCE = RepoEvidence(
    repo_url="https://github.com/synthetic/opencycle",
    repo_name="opencycle",
    description="Synthetic sample: a bike-share rebalancing prototype built for HackPack's examples",
    readme_content=(
        "# OpenCycle (synthetic sample)\n\n"
        "A prototype that suggests when to move bikes between stations. "
        "This repository exists only as sample input for HackPack."
    ),
    file_tree=["app/main.py", "app/rebalancer.py", "tests/test_rebalancer.py", "requirements.txt"],
    tech_stack=[
        TechStackItem(name="fastapi", version="0.115.0", category="framework", evidence_file="requirements.txt"),
        TechStackItem(name="plotly", version="5.24.0", category="library", evidence_file="requirements.txt"),
    ],
    source_excerpts={
        "app/main.py": "def main():\n    return 'start the demo app'\n",
        "app/rebalancer.py": (
            "def suggest_move(stations):\n"
            "    low = [s for s in stations if s['bikes'] < 3]\n"
            "    return low[0] if low else None\n"
        ),
    },
    test_files=["tests/test_rebalancer.py"],
    test_excerpts={
        "tests/test_rebalancer.py": "def test_suggest_move():\n    assert suggest_move([{'bikes': 0}]) is not None\n"
    },
    has_tests=True,
    demo_urls=[],
    primary_language="Python",
    languages={"Python": 1200},
    analysis_warnings=["Synthetic sample data; not a real repository."],
)

BRIEF = HackathonBrief(
    event_name="Sample City Mobility Hack (synthetic)",
    theme="Sustainable urban mobility",
    judging_criteria=["Innovation", "Technical execution", "Impact", "Demo quality"],
    pitch_duration_minutes=3,
)

TEAM = TeamContext(
    problem_statement="Bike-share stations run empty during morning commutes, so riders give up and take other transport.",
    target_users="Daily commuters and bike-share operators",
    future_plans="Add real station feeds and evaluate with operator data.",
)


def main() -> None:
    OUT.mkdir(exist_ok=True)
    deck = build_fallback_pitch(SYNTHETIC_EVIDENCE, BRIEF, TEAM)
    deck = verify_claims(deck, SYNTHETIC_EVIDENCE, TEAM)

    (OUT / "sample_deck.pptx").write_bytes(generate_pptx(deck))
    (OUT / "sample_script.md").write_text(generate_script(deck), encoding="utf-8")
    plan = build_demo_plan(SYNTHETIC_EVIDENCE, deck, demo_duration_seconds=180)
    (OUT / "sample_demo_checklist.md").write_text(generate_demo_checklist(plan, deck.project_name), encoding="utf-8")
    summary = {
        "notice": "Synthetic sample generated by scripts/make_sample_output.py. OpenCycle is not a real project.",
        "generation_mode": deck.generation_mode,
        "slide_count": len(deck.slides),
        "total_duration_seconds": deck.total_duration_seconds,
    }
    (OUT / "sample_generation_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print("sample_output regenerated (synthetic data).")


if __name__ == "__main__":
    main()
